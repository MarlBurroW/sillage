import assert from 'node:assert/strict'
import { join } from 'node:path'
import { checkAutomation } from './automation-navigation-flow.mjs'

// Exercise real persistence and script trials without starting an agent session.
export async function checkSchedule(context, origin, project, width, profile, shots) {
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.setDefaultTimeout(15000)
  await page.goto(`${origin}/p/${project.id}/schedules`)
  await page.getByRole('button', { name: 'Nouvelle automatisation', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const go = async (name) => {
    await dialog.getByRole('tab', { name, exact: true }).click()
    await dialog.getByRole('tabpanel', { name, exact: true }).waitFor()
  }
  const name = `Navigation ${profile} ${width}`
  await dialog.getByLabel('Nom', { exact: true }).fill(name)
  await dialog.getByLabel('Prompt', { exact: true }).fill('Analyse les versions sans lancer de session dans cet essai.')
  const requestTab = dialog.getByRole('tab', { name: 'Demande', exact: true })
  await requestTab.focus()
  await requestTab.press('ArrowRight')
  assert.equal(await dialog.getByRole('tab', { name: 'Calendrier', exact: true }).getAttribute('aria-selected'), 'true')
  await dialog.getByLabel('Tous les', { exact: true }).fill('0')
  await go('Agent')
  const create = dialog.getByRole('button', { name: 'Créer la tâche', exact: true })
  assert.equal(await create.isDisabled(), true)
  await dialog.getByRole('button', { name: 'À compléter : Calendrier', exact: true }).click()
  await dialog.getByRole('radio', { name: 'Cron', exact: true }).click()
  await dialog.getByLabel('Motif cron', { exact: true }).fill('invalid')
  assert.equal(await create.isDisabled(), true)
  await dialog.getByRole('button', { name: 'En semaine, 9 h', exact: true }).click()
  assert.equal(await dialog.getByLabel('Motif cron', { exact: true }).inputValue(), '0 9 * * 1-5')
  await dialog.getByRole('radio', { name: 'Ponctuel', exact: true }).click()
  await dialog.getByLabel('Date et heure', { exact: true }).fill('2020-01-01T09:00')
  await dialog.getByText('Cette date est passée.', { exact: true }).waitFor()
  await dialog.getByRole('radio', { name: 'Intervalle', exact: true }).click()
  await dialog.getByLabel('Tous les', { exact: true }).fill('2')
  await go('Agent')
  await dialog.getByRole('combobox', { name: 'Agent', exact: true }).click()
  await page.getByRole('option', { name: 'Codex', exact: true }).click()
  await go('Garde-fous')
  await dialog.getByLabel('Durée maximale (min)', { exact: true }).fill('17')
  await dialog.getByRole('switch').click()
  await dialog.getByLabel('Attente maximale d’une réponse (heures)', { exact: true }).fill('6')
  await dialog.getByRole('button', { name: 'Ajouter une vérification', exact: true }).click()
  const editor = dialog.locator('[data-check-section] .cm-content')
  await editor.fill('echo "Navigation conservée"; exit 10')
  await dialog.getByLabel('Délai (s)', { exact: true }).fill('0')
  await go('Demande')
  assert.equal(await create.isDisabled(), true)
  await dialog.getByRole('button', { name: 'À compléter : Garde-fous', exact: true }).click()
  await dialog.getByLabel('Délai (s)', { exact: true }).fill('15')
  await dialog.getByRole('button', { name: 'Tester', exact: true }).click()
  await dialog.locator('[data-check-result="skip"]').waitFor()
  const panel = dialog.getByRole('tabpanel', { name: 'Garde-fous', exact: true })
  const scroll = await panel.evaluate((el) => { el.scrollTop = el.scrollHeight; return el.scrollTop })
  await go('Demande')
  assert.equal(await dialog.getByLabel('Nom', { exact: true }).inputValue(), name)
  await go('Garde-fous')
  assert.equal(await panel.evaluate((el) => el.scrollTop), scroll)
  await dialog.locator('[data-check-result="skip"]').getByText('Navigation conservée', { exact: true }).waitFor()

  // Header, categories and save action stay in view even on low and narrow screens.
  const original = page.viewportSize()
  for (const viewport of [original, ...(width === 390 ? [{ width: 320, height: 568 }, { width: 844, height: 390 }] : [])]) {
    await page.setViewportSize(viewport)
    for (const tab of ['Demande', 'Calendrier', 'Agent', 'Garde-fous']) {
      await go(tab)
      const active = dialog.getByRole('tabpanel', { name: tab, exact: true })
      await active.evaluate((el) => { el.scrollTop = el.scrollHeight })
      const bounds = await create.boundingBox()
      const nav = await dialog.getByRole('tablist').boundingBox()
      assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= viewport.height + 1)
      assert.ok(nav.y >= 0)
      assert.ok(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth + 1))
      await page.screenshot({ path: join(shots, `${profile}-${viewport.width}-schedule-${tab === 'Garde-fous' ? 'safeguards' : tab === 'Demande' ? 'request' : tab === 'Agent' ? 'agent' : 'calendar'}.png`), animations: 'disabled' })
    }
  }
  await page.setViewportSize(original)
  await go('Demande')
  const savedResponse = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith(`/projects/${project.id}/schedules`))
  await create.click()
  const response = await savedResponse
  assert.ok(response.ok(), await response.text())
  const saved = await response.json()
  assert.equal(saved.agent, 'codex')
  assert.equal(saved.config.agent, 'codex')
  assert.equal(saved.maxDurationMinutes, 17)
  assert.equal(saved.decisionsEnabled, true)
  assert.equal(saved.decisionMaxHours, 6)
  assert.equal(saved.check.script, 'echo "Navigation conservée"; exit 10')
  assert.equal(saved.check.timeoutSeconds, 15)
  assert.deepEqual(saved.cadence, { kind: 'interval', minutes: 2880 })
  await dialog.waitFor({ state: 'hidden' })
  const card = page.locator(`[data-schedule="${name}"]`)
  await card.getByRole('button', { name: 'Modifier', exact: true }).click()
  await go('Garde-fous')
  assert.equal(await dialog.getByLabel('Durée maximale (min)', { exact: true }).inputValue(), '17')
  await go('Calendrier')
  assert.equal(await dialog.getByLabel('Tous les', { exact: true }).inputValue(), '2')
  await go('Demande')
  await dialog.getByLabel('Nom', { exact: true }).fill(`${name} modifiée`)
  await go('Agent')
  const patch = page.waitForResponse((r) => r.request().method() === 'PATCH' && r.url().endsWith(`/schedules/${saved.id}`))
  await dialog.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  assert.ok((await patch).ok())
  await dialog.waitFor({ state: 'hidden' })
  await context.request.delete(`${origin}/api/schedules/${saved.id}`)

  // Short webhook creation keeps its template flow and can switch back without losing the prompt.
  await page.getByRole('button', { name: 'Nouvelle automatisation', exact: true }).click()
  await dialog.getByLabel('Prompt', { exact: true }).fill('Demande conservée')
  await dialog.getByRole('radio', { name: /Par un webhook/ }).click()
  assert.equal(await dialog.getByRole('tablist').count(), 0)
  await dialog.getByRole('radio', { name: /À heure fixe/ }).click()
  assert.equal(await dialog.getByLabel('Prompt', { exact: true }).inputValue(), 'Demande conservée')
  await dialog.getByRole('radio', { name: /Par un webhook/ }).click()
  const webhookResponse = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith(`/projects/${project.id}/schedules`))
  await dialog.getByRole('button', { name: 'Créer et configurer', exact: true }).click()
  const webhook = await webhookResponse
  assert.ok(webhook.ok(), await webhook.text())
  const automation = await webhook.json()
  assert.equal(automation.cadence.kind, 'webhook')
  await page.waitForURL(`**/schedules/${automation.id}`)
  await checkAutomation(page, context, origin, automation, width, profile, shots)
  await context.request.delete(`${origin}/api/schedules/${automation.id}`)
  assert.deepEqual(errors, [])
  await page.close()
}

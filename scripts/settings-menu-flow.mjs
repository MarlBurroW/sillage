import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function checkSettingsMenu(context, origin, width, profile, shots, admin = true) {
  const page = await context.newPage()
  await context.addInitScript(() => localStorage.setItem('sillage.locale', 'fr'))
  await page.goto(`${origin}/settings${width >= 1024 ? '/apparence' : ''}`)
  const menu = page.getByRole('navigation', { name: 'Réglages', exact: true })
  const search = menu.getByRole('searchbox', { name: 'Rechercher un réglage', exact: true })
  await search.waitFor()
  await search.fill('mot de passe')
  assert.equal(await menu.getByRole('link').count(), profile === 'desktop' ? 0 : 1)
  if (profile === 'desktop') await menu.getByText('Aucune catégorie ne correspond.', { exact: true }).waitFor()
  await search.fill('dictee')
  assert.equal(await menu.getByRole('link').count(), admin ? 1 : 0)
  await search.fill('apparence')
  const appearance = menu.getByRole('link', { name: /Apparence/ })
  await appearance.waitFor()
  await appearance.click()
  await page.getByRole('navigation', { name: 'Catégories d’apparence', exact: true }).waitFor()
  if (width < 1024) await page.locator('main').getByRole('link', { name: 'Réglages', exact: true }).click()
  assert.equal(await search.inputValue(), 'apparence')
  await search.press('Escape')
  await menu.getByRole('button', { name: /^Agents/ }).click()
  assert.equal(await menu.getByRole('button', { name: /^Agents/ }).getAttribute('aria-expanded'), 'true')
  await menu.getByRole('button', { name: /^Agents/ }).click()
  assert.equal(await menu.getByRole('button', { name: /^Agents/ }).getAttribute('aria-expanded'), 'false')
  await search.fill('grok')
  await menu.getByRole('link', { name: /^Comptes Grok/ }).waitFor()
  await menu.getByRole('button', { name: 'Effacer la recherche', exact: true }).click()
  assert.equal(await search.inputValue(), '')
  await menu.locator('[data-settings-list]').evaluate((el) => { el.scrollTop = el.scrollHeight })
  assert.ok((await search.boundingBox()).y >= 0)
  await page.screenshot({ path: join(shots, `${profile}-${width}-${admin ? 'admin' : 'reader'}-settings-menu.png`), animations: 'disabled' })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.goto(`${origin}/settings/comptes-grok`)
  if (width < 1024) await page.locator('main').getByRole('link', { name: 'Réglages', exact: true }).click()
  assert.equal(await menu.getByRole('button', { name: /^Agents/ }).getAttribute('aria-expanded'), 'true')
  await page.close()
}

import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function checkNewsNavigation(context, origin, width, profile) {
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.setDefaultTimeout(15000)
  const original = (await (await context.request.get(`${origin}/api/me/settings`)).json()).news
  await page.goto(`${origin}/settings/veille`)
  const nav = page.getByRole('navigation', { name: 'Rubriques de veille', exact: true })
  const go = async (name) => {
    await nav.getByRole('link', { name, exact: true }).click()
    await nav.getByRole('link', { name, exact: true }).and(page.locator('[aria-current=page]')).waitFor()
  }
  const articles = page.getByRole('region', { name: 'Articles récents', exact: true })
  await articles.getByRole('status').filter({ hasText: '23 résultats' }).waitFor()
  assert.equal(await articles.locator('li').count(), 10)
  await articles.getByRole('button', { name: 'Suivant', exact: true }).click()
  await articles.getByRole('status').filter({ hasText: 'Page 2 / 3' }).waitFor()
  await articles.getByRole('button', { name: 'Suivant', exact: true }).click()
  assert.equal(await articles.locator('li').count(), 3)
  const search = page.getByRole('searchbox', { name: 'Rechercher un article', exact: true })
  await search.fill('elephant')
  await articles.getByRole('link', { name: /Éléphant/ }).waitFor()
  assert.equal(await articles.locator('li').count(), 1)
  await go('Sources')
  const sources = page.getByRole('region', { name: 'Sources', exact: true })
  const sourceSearch = page.getByRole('searchbox', { name: 'Rechercher une source', exact: true })
  assert.equal(await sources.locator('[data-news-sources] [role=switch]').count(), 6)
  await sourceSearch.fill('feed-12')
  await sources.getByText('https://example.org/feed-12', { exact: true }).waitFor()
  await sourceSearch.fill('')
  await sources.getByRole('button', { name: 'Suivant', exact: true }).click()
  await sources.getByRole('button', { name: 'Suivant', exact: true }).click()
  await sources.getByRole('status').filter({ hasText: 'Page 3 / 3' }).waitFor()
  await sources.getByRole('button', { name: 'Retirer Flux 12', exact: true }).click()
  await sources.getByRole('status').filter({ hasText: 'Page 2 / 2' }).waitFor()
  await sources.getByRole('button', { name: 'Ajouter la source', exact: true }).click()
  const url = page.getByLabel('Ajouter un flux RSS ou Atom', { exact: true })
  await url.fill('https://example.org/atom')
  await page.getByRole('button', { name: 'Tester le flux', exact: true }).click()
  const preview = page.locator('[data-news-preview]')
  await preview.waitFor()
  await go('Articles récents')
  assert.equal(await search.inputValue(), 'elephant')
  await go('Sources')
  assert.equal(await url.inputValue(), 'https://example.org/atom')
  await preview.waitFor()
  await page.goBack()
  await articles.waitFor()
  await page.goForward()
  await preview.waitFor()
  const saveUrl = `${origin}/api/me/news`
  await page.route(saveUrl, (route) => route.fulfill({ status: 503, json: { error: { code: 'test_failure', message: 'RSS save failed for test' } } }))
  await preview.getByRole('button', { name: 'Ajouter la source', exact: true }).click()
  await page.getByText('RSS save failed for test', { exact: true }).waitFor()
  assert.equal(await url.inputValue(), 'https://example.org/atom')
  await preview.waitFor()
  await page.unroute(saveUrl)
  await preview.getByRole('button', { name: 'Ajouter la source', exact: true }).click()
  await sources.getByText('https://example.org/atom', { exact: true }).waitFor()
  await sources.getByRole('status').filter({ hasText: 'Page 3 / 3' }).waitFor()
  const saved = (await (await context.request.get(`${origin}/api/me/settings`)).json()).news
  assert.ok(saved.sources.some((source) => source.url === 'https://example.org/atom'))
  await sources.getByRole('button', { name: 'Ajouter la source', exact: true }).click()
  await url.fill('https://example.org/atom')
  await page.getByText('Ce flux est déjà dans vos sources.', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Tester le flux', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Annuler', exact: true }).click()
  await go('Articles récents')
  await search.fill('')
  await page.screenshot({ path: join('/var/tmp', `sillage-${profile}-${width}-news-articles.png`), animations: 'disabled' })
  assert.ok(await page.locator('main').evaluate((el) => el.scrollHeight <= el.clientHeight + 1))
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await go('Sources')
  await page.screenshot({ path: join('/var/tmp', `sillage-${profile}-${width}-news-sources.png`), animations: 'disabled' })
  await page.reload()
  await sources.waitFor()
  const full = { enabled: true, sources: Array.from({ length: 20 }, (_, i) => ({ url: `https://example.org/feed-${i}`, enabled: true })) }
  assert.ok((await context.request.put(saveUrl, { data: full })).ok())
  await page.reload()
  assert.equal(await sources.getByRole('button', { name: 'Ajouter la source', exact: true }).isDisabled(), true)
  assert.ok((await context.request.put(saveUrl, { data: { enabled: false, sources: [] } })).ok())
  await page.reload()
  await page.getByText('Ajoutez un flux pour composer votre veille.', { exact: true }).waitFor()
  await go('Articles récents')
  await page.getByText('Activez la veille pour collecter les articles de vos sources.', { exact: true }).waitFor()
  assert.ok((await context.request.put(saveUrl, { data: original })).ok())
  assert.deepEqual(errors, [])
  await page.close()
}

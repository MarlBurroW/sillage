import assert from 'node:assert/strict'
import { join } from 'node:path'

// Navigation must preserve the shared draft and bench on both editions and at narrow widths.
export async function checkAutomation(page, context, origin, task, width, profile, shots) {
  const views = page.getByRole('navigation', { name: 'Automatisation', exact: true })
  const sections = page.getByRole('navigation', { name: 'Rubriques de configuration', exact: true })
  const bench = page.getByRole('region', { name: 'Banc d’essai', exact: true })
  const view = async (name) => {
    await views.getByRole('link', { name, exact: true }).click()
    await views.getByRole('link', { name, exact: true }).and(page.locator('[aria-current=page]')).waitFor()
  }
  const section = async (name) => {
    await view('Configuration')
    await sections.getByRole('link', { name, exact: true }).click()
    await page.getByRole('region', { name, exact: true }).waitFor()
  }
  await views.waitFor()
  assert.equal(await bench.isVisible(), width >= 1280)
  await section('Prompt')
  const prompt = page.getByRole('textbox', { name: 'Prompt', exact: true })
  await prompt.fill('Brouillon : {{payload.issue.number}}')
  await view('Historique')
  await page.getByText(/Aucun appel reçu pour l’instant/).waitFor()
  await view('Tester')
  await bench.locator('pre').filter({ hasText: 'Brouillon : 42' }).waitFor()
  await bench.getByRole('tab', { name: 'Appel', exact: true }).click()
  await bench.getByRole('tab', { name: 'Modifier', exact: true }).click()
  const payload = '{"action":"labeled","label":{"name":"sillage"},"issue":{"number":27,"title":"Navigation"},"sender":{"login":"alex"}}'
  await bench.locator('.cm-content').fill(payload)
  await view('Historique')
  await view('Tester')
  assert.equal(await bench.locator('.cm-content').textContent(), payload)
  await bench.getByRole('tab', { name: 'Explorer', exact: true }).click()
  await bench.getByRole('button', { name: 'Insérer {{payload.issue.number}} dans le prompt', exact: true }).click()
  await prompt.waitFor()
  assert.equal(new URL(page.url()).searchParams.get('section'), 'prompt')
  assert.equal(await prompt.inputValue(), 'Brouillon : {{payload.issue.number}}{{payload.issue.number}}')
  assert.equal(await prompt.evaluate((el) => document.activeElement === el), true)
  await view('Tester')
  await bench.getByRole('button', { name: 'Filtrer sur payload.sender.login', exact: true }).click()
  await page.getByRole('region', { name: 'Conditions', exact: true }).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('section'), 'trigger')
  assert.equal(await page.getByRole('textbox', { name: 'Champ', exact: true }).last().inputValue(), 'payload.sender.login')
  await page.getByRole('button', { name: 'Ajouter un script', exact: true }).click()
  const script = page.getByRole('region', { name: 'Conditions', exact: true }).locator('.cm-content')
  await script.fill('export default () => ({ vars: { note: "conservée" } })')
  const conditionPanel = page.getByRole('region', { name: 'Conditions', exact: true })
  const scroll = await conditionPanel.evaluate((el) => { el.scrollTop = el.scrollHeight; return el.scrollTop })
  await section('Agent')
  await page.getByRole('combobox', { name: 'Agent', exact: true }).click()
  await page.getByRole('option', { name: 'Codex', exact: true }).click()
  await section('Garde-fous')
  await page.getByLabel('Durée maximale (min)', { exact: true }).fill('23')
  await page.getByRole('switch', { name: "L'agent peut te demander de trancher", exact: true }).click()
  await page.getByLabel('Attente maximale d’une réponse (heures)', { exact: true }).fill('0')
  await view('Historique')
  const save = page.getByRole('button', { name: 'Enregistrer', exact: true })
  assert.equal(await save.isDisabled(), true)
  await page.getByRole('button', { name: 'À compléter : Garde-fous', exact: true }).click()
  await page.getByLabel('Attente maximale d’une réponse (heures)', { exact: true }).fill('5')
  await section('Conditions')
  assert.equal(await script.textContent(), 'export default () => ({ vars: { note: "conservée" } })')
  assert.equal(await conditionPanel.evaluate((el) => el.scrollTop), scroll)
  await page.goBack()
  await page.getByRole('region', { name: 'Garde-fous', exact: true }).waitFor()
  await page.goForward()
  await conditionPanel.waitFor()

  const original = page.viewportSize()
  for (const viewport of [original, ...(width === 390 ? [{ width: 320, height: 568 }, { width: 844, height: 390 }, { width: 1024, height: 768 }] : [])]) {
    await page.setViewportSize(viewport)
    for (const name of ['Connexion', 'Conditions', 'Prompt', 'Agent', 'Garde-fous']) {
      await section(name)
      const panel = page.getByRole('region', { name, exact: true })
      await panel.evaluate((el) => { el.scrollTop = el.scrollHeight })
      const bounds = await save.boundingBox()
      assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= viewport.height + 1)
      assert.ok((await sections.boundingBox()).y >= 0)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      assert.ok(await page.locator('main').evaluate((el) => el.scrollHeight <= el.clientHeight + 1))
      if (name === 'Prompt' || name === 'Agent') {
        await page.screenshot({ path: join(shots, `${profile}-${viewport.width}-automation-${name.toLowerCase()}.png`), animations: 'disabled' })
      }
    }
    await view('Tester')
    await bench.getByRole('tab', { name: 'Prompt', exact: true }).click()
    await bench.locator('pre').filter({ hasText: 'Brouillon : 2727' }).waitFor()
    await page.screenshot({ path: join(shots, `${profile}-${viewport.width}-automation-test.png`), animations: 'disabled' })
    await view('Historique')
    await page.screenshot({ path: join(shots, `${profile}-${viewport.width}-automation-history.png`), animations: 'disabled' })
  }
  await page.setViewportSize(original)

  // A rejected save leaves both the draft and retry action available, without an unhandled promise.
  const hookUrl = `${origin}/api/schedules/${task.id}/webhook`
  await page.route(hookUrl, (route) => route.request().method() === 'PATCH'
    ? route.fulfill({ status: 503, json: { error: { code: 'test_save_failure', message: 'Save failure for navigation test' } } })
    : route.continue())
  await save.click()
  await page.getByText('Save failure for navigation test', { exact: true }).waitFor()
  await section('Prompt')
  assert.equal(await prompt.inputValue(), 'Brouillon : {{payload.issue.number}}{{payload.issue.number}}')
  await page.unroute(hookUrl)
  await save.click()
  await page.getByText('Modifications non enregistrées', { exact: true }).waitFor({ state: 'hidden' })
  await save.waitFor({ state: 'hidden' })
  const tasks = await (await context.request.get(`${origin}/api/schedules`)).json()
  const saved = tasks.find((entry) => entry.id === task.id)
  assert.equal(saved.agent, 'codex')
  assert.equal(saved.maxDurationMinutes, 23)
  assert.equal(saved.decisionMaxHours, 5)
  assert.equal(saved.webhook.conditions.rules.at(-1).path, 'payload.sender.login')
  assert.equal(saved.webhook.script, 'export default () => ({ vars: { note: "conservée" } })')
  await view('Tester')
  await page.reload()
  await views.getByRole('link', { name: 'Tester', exact: true }).and(page.locator('[aria-current=page]')).waitFor()
  await section('Prompt')
  assert.equal(await prompt.inputValue(), saved.prompt)
  await prompt.fill('Brouillon à annuler')
  await view('Historique')
  await page.getByRole('button', { name: 'Annuler', exact: true }).click()
  await section('Prompt')
  assert.equal(await prompt.inputValue(), saved.prompt)
}

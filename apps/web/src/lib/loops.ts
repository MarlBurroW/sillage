import { loopKey, type ChatState } from './chat-fold'

/**
 * Armed loops enriched with information the CLI does not count (invariant I2). `SessionCronSummary`
 * provides cadence and instruction only, neither next fire time nor fire count. The first is
 * undisplayable anyway because CLI jitter can reach half the interval; derive the second from the
 * log, where each wakeup records its reinjected instruction.
 */

export interface ArmedLoop {
  id: string
  /** Five-field cron expression as held by the CLI. */
  schedule: string
  recurring: boolean
  prompt: string
  /** Wakeups observed in this log. Zero before the loop first fires. */
  iterations: number
  /** Latest wakeup timestamp, null before any wakeup. */
  lastFiredAt: number | null
}

export function buildLoops(state: ChatState): ArmedLoop[] {
  return state.loops.map((loop) => {
    const fires = state.loopFires.get(loopKey(loop.prompt))
    return {
      id: loop.id,
      schedule: loop.schedule,
      recurring: loop.recurring,
      prompt: loop.prompt,
      iterations: fires?.count ?? 0,
      lastFiredAt: fires?.lastAt ?? null,
    }
  })
}

/**
 * Wakeup age at useful granularity. Units are identical in French and English; translate only the
 * surrounding phrase.
 */
export function formatAgo(ms: number): string {
  const minutes = Math.floor(ms / 60_000)
  if (minutes < 1) return '< 1 min'
  if (minutes < 60) return `${minutes} min`
  return `${Math.floor(minutes / 60)} h`
}

/**
 * Readable cadence for expressions generated by `/loop`. Deliberately partial: `/loop` only writes
 * steps and fixed minute/hour values. Other expressions come from handwritten requests and raw
 * syntax describes them better than approximate paraphrases.
 */
export function describeSchedule(schedule: string): string | null {
  const [minute, hour, dayOfMonth, month, dayOfWeek] = schedule.trim().split(/\s+/)
  if (minute === undefined || hour === undefined) return null
  if (dayOfMonth !== '*' || month !== '*' || dayOfWeek !== '*') return null

  const everyMinutes = /^\*\/(\d+)$/.exec(minute)
  if (everyMinutes && hour === '*') return `${everyMinutes[1]}m`

  const everyHours = /^\*\/(\d+)$/.exec(hour)
  if (everyHours && /^\d+$/.test(minute)) return `${everyHours[1]}h`

  if (/^\d+$/.test(minute) && hour === '*') return '1h'

  return null
}

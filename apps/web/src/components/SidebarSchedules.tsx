import { CalendarClock, ChevronRight, Plus } from 'lucide-react'
import { useMemo, useState, type ReactNode } from 'react'
import { NavLink } from 'react-router-dom'
import type { ConversationDto, ScheduledTaskDto } from '@sillage/protocol'
import { relativeDate } from '../lib/dates'
import { useTranslate } from '../lib/i18n'
import { SCHEDULE_STATE_LABELS, scheduleState, type ScheduleState } from '../lib/schedules'
import { cx } from './ui'

/** Runs shown beneath tasks; full history lives on Scheduling. */
const RUNS_SHOWN = 5

const STATE_DOTS: Record<ScheduleState, string> = {
  approval: 'bg-caution',
  running: 'bg-accent animate-pulse',
  paused: 'bg-line-strong',
  failed: 'bg-critical',
  done: 'bg-line-strong',
  waiting: 'bg-positive',
}

/**
 * Project scheduled tasks with collapsible runs. Move scheduleId threads here: hourly tasks would
 * add twenty-four daily rows and overwhelm active-work sessions. Reuse renderRun because opened
 * runs are ordinary conversations needing identical signals and menus.
 */
export function SidebarSchedules({
  projectId,
  tasks,
  conversations,
  focused,
  onNavigate,
  renderRun,
}: {
  projectId: string
  tasks: ScheduledTaskDto[]
  /** Project threads generated by runs across all tasks. */
  conversations: ConversationDto[]
  /**
   * Show an empty section for the current project so scheduling is discoverable; empty sections for
   * every project in the all-project view would only add noise.
   */
  focused: boolean
  onNavigate: () => void
  renderRun: (conversation: ConversationDto) => ReactNode
}) {
  const t = useTranslate()
  if (tasks.length === 0 && !focused) return null

  return (
    <li className="mt-2" data-sidebar-schedules>
      <NavLink
        to={`/p/${projectId}/schedules`}
        onClick={onNavigate}
        className="flex h-7 items-center gap-1.5 rounded px-1 text-[0.6875rem] font-semibold tracking-wider text-ink-faint uppercase transition-colors hover:text-ink-soft"
      >
        <CalendarClock size={11} className="shrink-0" />
        <span className="flex-1">{t('schedule.sidebar.heading')}</span>
        <span className="tabular-nums">{tasks.length}</span>
      </NavLink>
      <ul className="flex flex-col gap-px">
        {/*
         * Always show the add row like New Session so both sections read as lists of one project.
         * The new parameter opens the page form directly.
         */}
        <li>
          <NavLink
            to={`/p/${projectId}/schedules?new`}
            onClick={onNavigate}
            className="flex min-h-11 items-center gap-2 rounded-md px-2 text-[0.8125rem] text-ink-faint transition-colors hover:bg-surface-high hover:text-ink md:min-h-8 pointer-coarse:min-h-11"
          >
            <Plus size={13} className="shrink-0" />
            <span className="min-w-0 flex-1 truncate">{t('schedule.sidebar.new')}</span>
          </NavLink>
        </li>
        {tasks.map((task) => (
          <TaskRow
            key={task.id}
            task={task}
            conversations={conversations}
            onNavigate={onNavigate}
            renderRun={renderRun}
          />
        ))}
      </ul>
    </li>
  )
}

function TaskRow({
  task,
  conversations,
  onNavigate,
  renderRun,
}: {
  task: ScheduledTaskDto
  conversations: ConversationDto[]
  onNavigate: () => void
  renderRun: (conversation: ConversationDto) => ReactNode
}) {
  const t = useTranslate()
  const [open, setOpen] = useState(false)
  const state = scheduleState(task)
  // Archived runs remain accessible in page history; retain only fresh ones beneath tasks.
  const runs = useMemo(
    () =>
      conversations
        .filter((entry) => entry.scheduleId === task.id && !entry.archivedAt)
        .sort((a, b) => b.createdAt - a.createdAt),
    [conversations, task.id],
  )

  return (
    <li>
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((current) => !current)}
        title={`${task.name} · ${t(SCHEDULE_STATE_LABELS[state])}`}
        className="flex min-h-11 w-full items-center gap-1.5 rounded-md px-1 text-left text-sm text-ink-soft transition-colors hover:bg-surface-high hover:text-ink md:min-h-8 pointer-coarse:min-h-11"
      >
        <ChevronRight size={11} className={cx('shrink-0 text-ink-faint transition-transform', open && 'rotate-90')} />
        <span aria-hidden className={cx('size-1.5 shrink-0 rounded-full', STATE_DOTS[state])} />
        <span className="sr-only">{t(SCHEDULE_STATE_LABELS[state])}</span>
        <span className="min-w-0 flex-1 truncate">{task.name}</span>
        <span className="shrink-0 text-[0.6875rem] text-ink-faint">
          {task.lastRunAt ? relativeDate(task.lastRunAt) : t('schedule.fact.never')}
        </span>
      </button>
      {open ? (
        <ul className="mb-1 ml-2.5 flex flex-col gap-px border-l border-line pl-1">
          {runs.length === 0 ? (
            <li className="px-2 py-1.5 text-xs text-ink-faint">{t('schedule.history.empty')}</li>
          ) : (
            runs.slice(0, RUNS_SHOWN).map(renderRun)
          )}
          {runs.length > RUNS_SHOWN || task.runs.length > runs.length ? (
            <li>
              <NavLink
                // Webhook automations have their own page and call log.
                to={task.webhook ? `/p/${task.projectId}/schedules/${task.id}` : `/p/${task.projectId}/schedules`}
                onClick={onNavigate}
                className="flex min-h-9 items-center rounded px-2 text-xs text-ink-faint hover:bg-surface-high hover:text-ink-soft"
              >
                {t('schedule.sidebar.allRuns')}
              </NavLink>
            </li>
          ) : null}
        </ul>
      ) : null}
    </li>
  )
}
